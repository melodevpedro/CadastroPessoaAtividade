    private void jButton4ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton4ActionPerformed
        // Navegar para direita
        List<Pessoa> lstPessoa = telaPrincipal.getListaPessoa();
        posicao++; //posicao = posicao+1
        if(posicao < lstPessoa.size()){
            Pessoa pessoa = lstPessoa.get(posicao);
            //posicao++; //posicao = posicao+1
            txtNome.setText(pessoa.getNome());
            txtEndereco.setText(pessoa.getEndereco());
            txtEmail.setText(pessoa.getEmail());
        }else{
            JOptionPane.showMessageDialog(null, "Não existem mais pessoas no cadastro");
            posicao = -1;
            limparTela();
        }
    }//GEN-LAST:event_jButton4ActionPerformed

    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        // Navegar para à esquerda
        List<Pessoa> lstPessoa = telaPrincipal.getListaPessoa();
        posicao--; //posicao = posicao-1
        if(posicao > -1){
            Pessoa pessoa = lstPessoa.get(posicao);
            txtNome.setText(pessoa.getNome());
            txtEndereco.setText(pessoa.getEndereco());
            txtEmail.setText(pessoa.getEmail());
        }else{
            JOptionPane.showMessageDialog(null, "Não existem mais pessoas no cadastro");
            posicao = -1;
            limparTela();
        }
    }//GEN-LAST:event_jButton3ActionPerformed

    private void jButton5ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton5ActionPerformed
                                                
    // Verifico se tem alguma pessoa selecionada
    if (posicao == -1) {
        JOptionPane.showMessageDialog(
                this,
                "Não existe uma pessoa para excluir."
        );
        return;
    }

    // Pede confirmação ao usuário
    int resposta = JOptionPane.showConfirmDialog(
            this,
            "Deseja realmente excluir essa pessoa?",
            "Confirmar exclusão",
            JOptionPane.YES_NO_OPTION
    );
    //se a opção for Yes , ele remove 
    if (resposta == JOptionPane.YES_OPTION) {
        
        telaPrincipal.removerPessoaLista(posicao);

        
        List<Pessoa> lstPessoa = telaPrincipal.getListaPessoa();

        if (lstPessoa.isEmpty()) {
            posicao = -1;
            limparTela();
        } else if (posicao >= lstPessoa.size()) {
          
            posicao = lstPessoa.size() - 1;

            Pessoa pessoa = lstPessoa.get(posicao);

            txtNome.setText(pessoa.getNome());
            txtEndereco.setText(pessoa.getEndereco());
            txtEmail.setText(pessoa.getEmail());
        } else {
           
            Pessoa pessoa = lstPessoa.get(posicao);

            txtNome.setText(pessoa.getNome());
            txtEndereco.setText(pessoa.getEndereco());
            txtEmail.setText(pessoa.getEmail());
        }

        JOptionPane.showMessageDialog(
                this,
                "Essa pessoa foi excluída com sucesso!"
        );
    }
        
        
        
        
        
        
    }//GEN-LAST:event_jButton5ActionPerformed


